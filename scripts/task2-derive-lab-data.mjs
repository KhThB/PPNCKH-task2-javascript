#!/usr/bin/env node
/**
 * Task 2/3 — sinh src/data/lab-images-a.ts và lab-images-b.ts từ src/data/image-audit.ts (tệp của Task 1, chỉ đọc).
 *
 * Trang /lab/c chỉ cần vài trường để hiển thị: tên, vùng, tiêu đề, alt, đường dẫn JPEG của A
 * và thông tin nguồn ảnh ở chân trang. image-audit.ts còn chứa bảng byte, PSNR, ablation…
 * phục vụ hồ sơ Task 1, nên khi trang thí nghiệm import nó thì cả ~20 KB dữ liệu đó bị gửi
 * xuống và parse dù giao diện không dùng.
 *
 *   node scripts/task2-derive-lab-data.mjs          # ghi lại tệp
 *   node scripts/task2-derive-lab-data.mjs --check  # báo lỗi nếu tệp lệch với image-audit.ts
 *
 * Cần Node 22.18+ (import trực tiếp tệp .ts).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);
const { imageAudit } = await import(new URL("src/data/image-audit.ts", root).href);

const credit = (image) => ({
  artist: image.source.artist,
  license: image.source.license,
  title: image.source.title,
  sourceUrl: image.source.sourceUrl,
});

const outputs = [
  {
    file: "src/data/lab-images-a.ts",
    images: imageAudit.images.map((image) => ({
      id: image.id,
      place: image.place,
      region: image.region,
      title: image.title,
      alt: image.alt,
      src: image.versionA.path,
      credit: credit(image),
    })),
    header: "Chỉ giữ các trường mà trang thí nghiệm hiển thị khi giao ảnh theo cách của bản A.",
    type: `export type LabImageA = {
  id: string;
  place: string;
  region: "Bắc" | "Trung" | "Nam";
  title: string;
  alt: string;
  src: string;
  credit: { artist: string; license: string; title: string; sourceUrl: string };
};

export const labImagesA: LabImageA[] = `,
  },
  {
    file: "src/data/lab-images-b.ts",
    images: imageAudit.images.map((image) => ({
      id: image.id,
      place: image.place,
      region: image.region,
      title: image.title,
      alt: image.alt,
      slot: image.slot,
      sizes: image.sizes,
      width: image.versionA.width,
      height: image.versionA.height,
      avif: image.versionB.avif.map((item) => ({ path: item.path, width: item.width })),
      webp: image.versionB.webp.map((item) => ({ path: item.path, width: item.width })),
      fallback: image.versionB.fallback.path,
      credit: credit(image),
    })),
    header:
      "Chỉ giữ các trường mà trang thí nghiệm cần để giao ảnh theo cách của bản B (dùng cho bản D).",
    type: `type Candidate = { path: string; width: number };

export type LabImageB = {
  id: string;
  place: string;
  region: "Bắc" | "Trung" | "Nam";
  title: string;
  alt: string;
  slot: string;
  sizes: string;
  width: number;
  height: number;
  avif: Candidate[];
  webp: Candidate[];
  fallback: string;
  credit: { artist: string; license: string; title: string; sourceUrl: string };
};

export const labImagesB: LabImageB[] = `,
  },
];

let stale = false;
for (const out of outputs) {
  const target = fileURLToPath(new URL(out.file, root));
  const body = `/* Generated by scripts/task2-derive-lab-data.mjs from src/data/image-audit.ts. Do not edit by hand.
   ${out.header} */
${out.type}${JSON.stringify(out.images, null, 2)};
`;
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      /* chưa có tệp */
    }
    if (current !== body) {
      console.error(`${out.file} lệch với image-audit.ts — chạy lại script này.`);
      stale = true;
    } else console.log(`${out.file} khớp với image-audit.ts`);
  } else {
    writeFileSync(target, body);
    console.log(`Đã ghi ${out.file} (${out.images.length} ảnh, ${Buffer.byteLength(body)} B)`);
  }
}
if (stale) process.exit(1);
